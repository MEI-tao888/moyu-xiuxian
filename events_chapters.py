"""三回合短篇历练。每行依次为处境、稳/搏/险的选项与结局。

首层兼顾乡野凡俗与初入仙门；境界编号沿用炼气=0，不另添凡人境界。
这里只装配数据，选场景、结算与存档仍由 game.py 负责。
"""

CHAPTERS = {}
CHAPTER_EVENTS = []


def _chapter(cid, title, lo, hi, rows):
    ids = []
    for step, row in enumerate(rows.strip().splitlines()):
        text, sl, so, rl, ro, rk, gl, go, gk = row.split('|')
        eid = '%s_%d' % (cid, step + 1)
        ids.append(eid)
        CHAPTER_EVENTS.append({
            'id': eid, 'text': text, 'flag': None,
            'min_realm': lo, 'max_realm': hi, 'chapter': cid,
            'title': title, 'step': step, 'total': 3,
            'opts': [('safe', '【稳】' + sl, so, None),
                     ('risky', '【搏】' + rl, ro, rk),
                     ('gamble', '【险】' + gl, go, gk)],
        })
    CHAPTERS[cid] = {'title': title, 'events': ids}


